import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
for (const folder of ['dsh-harmony', 'harmony-navigation']) {
  const path = resolve(root, 'plugins', folder);
  const pkg = JSON.parse(await readFile(resolve(path, 'package.json')));
  const input = await readFile(resolve(path, 'client.mjs'), 'utf8');
  if (/^\s*(?:import\s|export\s+(?:\*|\{))/m.test(input)) throw Error('Client entry must be self-contained');
  const source = input.replace(/^export /gm, '');
  const output = `// Generated by scripts/build-plugin-client.mjs; edit client.mjs.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory: () => {\n${source.split('\n').map(line => line ? '    ' + line : '').join('\n')}\n    return { inject, apply };\n  }\n});\n`;
  await writeFile(resolve(path, 'client.browser.js'), output);
}
